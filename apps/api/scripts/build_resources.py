def validate_and_save() -> None:
    with open(TAXONOMY_PATH, encoding="utf-8") as f:
        tax_skills = json.load(f)

    valid_skill_ids = {s["id"] for s in tax_skills}

    print(f"Loaded {len(valid_skill_ids)} skills from taxonomy.json.")
    print(f"Total curated resources defined: {len(RESOURCES)}")

    seen_res_ids = set()
    covered_skills = set()
    invalid_skills = set()

    for r in RESOURCES:
        rid = str(r["id"])
        if rid in seen_res_ids:
            raise ValueError(f"Duplicate resource id: {rid}")
        seen_res_ids.add(rid)

        url = str(r["url"])
        assert url.startswith("https://"), f"URL must be https: {url}"
        assert r["type"] in ("course", "doc", "video", "tutorial"), f"Invalid type: {r['type']}"
        assert r["difficulty"] in ("beginner", "intermediate", "advanced"), f"Invalid difficulty: {r['difficulty']}"

        raw_skill_ids = r["skill_ids"]
        assert isinstance(raw_skill_ids, list)
        for sid in raw_skill_ids:
            sid_str = str(sid)
            if sid_str not in valid_skill_ids:
                invalid_skills.add(sid_str)
            else:
                covered_skills.add(sid_str)

    if invalid_skills:
        raise ValueError(f"Encountered skill_ids not in taxonomy: {invalid_skills}")

    print(f"Total unique skills covered: {len(covered_skills)}")

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(RESOURCES, f, indent=2)

    print(f"Successfully saved {len(RESOURCES)} resources to {OUTPUT_PATH}")


if __name__ == "__main__":
    validate_and_save()
