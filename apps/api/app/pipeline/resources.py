"""Curated educational resource catalog loader and matching engine.
Ensures every resource link shown to the user is verified, free or high-reputation,
and NEVER hallucinated or generated by an LLM.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Literal
from urllib.parse import quote_plus

from pydantic import BaseModel, Field

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
RESOURCES_PATH = DATA_DIR / "resources.json"


class ResourceItem(BaseModel):
    id: str
    type: Literal["course", "doc", "video", "tutorial"]
    title: str
    platform: str
    url: str
    skill_ids: list[str] = Field(default_factory=list)
    difficulty: Literal["beginner", "intermediate", "advanced"] = "beginner"
    duration_hours: float | None = None
    duration_min: int | None = None
    free: bool = True
    language: str = "en"
    verified_at: str


class ResourceCatalog:
    def __init__(self, file_path: Path = RESOURCES_PATH) -> None:
        self.file_path = file_path
        self._resources_by_id: dict[str, ResourceItem] = {}
        self._resources_by_skill: dict[str, list[ResourceItem]] = {}
        self.load()

    def load(self) -> None:
        if not self.file_path.exists():
            self._resources_by_id = {}
            self._resources_by_skill = {}
            return

        with open(self.file_path, encoding="utf-8") as f:
            raw_data = json.load(f)

        self._resources_by_id.clear()
        self._resources_by_skill.clear()

        for item in raw_data:
            res = ResourceItem(**item)
            self._resources_by_id[res.id] = res
            for skill_id in res.skill_ids:
                if skill_id not in self._resources_by_skill:
                    self._resources_by_skill[skill_id] = []
                self._resources_by_skill[skill_id].append(res)

    @property
    def total_count(self) -> int:
        return len(self._resources_by_id)

    @property
    def covered_skill_count(self) -> int:
        return len(self._resources_by_skill)

    def get_by_id(self, resource_id: str) -> ResourceItem | None:
        return self._resources_by_id.get(resource_id)

    def get_for_skill(self, skill_id: str, limit: int = 3) -> list[ResourceItem]:
        items = self._resources_by_skill.get(skill_id, [])
        return items[:limit]

    def get_for_skills(self, skill_ids: list[str], limit_per_skill: int = 2) -> list[ResourceItem]:
        seen_ids: set[str] = set()
        results: list[ResourceItem] = []
        for sid in skill_ids:
            for item in self.get_for_skill(sid, limit=limit_per_skill):
                if item.id not in seen_ids:
                    seen_ids.add(item.id)
                    results.append(item)
        return results

    def build_fallback_search_url(self, skill_name: str) -> str:
        """Deterministic fallback URL if a skill lacks a specific curated entry in the catalog."""
        encoded = quote_plus(skill_name.strip())
        return f"https://devdocs.io/#q={encoded}"


# Global singleton instance
catalog = ResourceCatalog()

